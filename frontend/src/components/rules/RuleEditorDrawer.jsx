import React, { useMemo } from 'react';
import PropTypes from 'prop-types';
import {
  Box,
  Button,
  Divider,
  Drawer,
  FormControlLabel,
  IconButton,
  MenuItem,
  Stack,
  Switch,
  TextField,
  Tooltip,
  Typography,
} from '@mui/material';
import { Close } from '@mui/icons-material';
import { DOMAINS } from '../../utils/constants';
import { buildConditionGroups } from '../../utils/ruleUtils';
import { RuleActionsEditor } from './RuleActionsEditor';
import { RuleConditionsEditor } from './RuleConditionsEditor';
import { RuleSummaryPreview } from './RuleSummaryPreview';
import { RuleTesterPanel } from './RuleTesterPanel';

export function RuleEditorDrawer({
  editing,
  onChangeEditing,
  onClose,
  onUpdateConditions,
  canEditRules,
  lockedHint,
  sample,
  onSampleChange,
  onAutoGenerateSample,
  onRunTest,
  isTesting,
  testResult,
  isSaving,
  isDeleting,
  onSave,
  onRequestDelete,
}) {
  const conditionGroups = useMemo(() => buildConditionGroups(editing?.conditions || []), [editing?.conditions]);

  return (
    <Drawer anchor="right" open={!!editing} onClose={onClose} PaperProps={{ sx: { width: { xs: '100%', sm: 720 } } }}>
      {editing && (
        <Box sx={{ p: 3 }}>
          <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', mb: 2 }}>
            <Typography variant="h6">
              {editing.rule_id.startsWith('new_rule_') ? 'Create rule' : 'Edit rule'}
            </Typography>
            <IconButton aria-label="Close edit rule" onClick={onClose} size="small">
              <Close sx={{ fontSize: 18 }} />
            </IconButton>
          </Box>

          <Stack spacing={2}>
            <TextField
              label="Rule ID"
              value={editing.rule_id.startsWith('new_rule_') ? '(Autogenerated)' : editing.rule_id}
              disabled
              size="small"
            />
            <TextField
              label="Description"
              value={editing.description}
              onChange={(e) => onChangeEditing({ ...editing, description: e.target.value })}
              size="small"
            />
            <TextField
              select
              label="Domain"
              value={editing.domain}
              onChange={(e) => onChangeEditing({ ...editing, domain: e.target.value })}
              size="small"
              fullWidth
            >
              {DOMAINS.map((d) => (
                <MenuItem key={d} value={d}>
                  {d}
                </MenuItem>
              ))}
            </TextField>
            <FormControlLabel
              control={
                <Switch
                  checked={!!editing.is_active}
                  onChange={(e) => onChangeEditing({ ...editing, is_active: e.target.checked ? 1 : 0 })}
                />
              }
              label="Active"
            />
          </Stack>

          <Divider sx={{ my: 2.5 }} />

          <RuleSummaryPreview conditionsCount={editing.conditions.length} conditionGroups={conditionGroups} />

          <RuleConditionsEditor
            conditions={editing.conditions}
            conditionGroups={conditionGroups}
            ruleDomain={editing.domain}
            onUpdateConditions={onUpdateConditions}
          />

          <Divider sx={{ my: 2.5 }} />

          <RuleActionsEditor
            actions={editing.actions}
            ruleDomain={editing.domain}
            onUpdateActions={(actions) => onChangeEditing({ ...editing, actions })}
          />

          <Divider sx={{ my: 2.5 }} />

          <RuleTesterPanel
            sample={sample}
            onSampleChange={onSampleChange}
            onAutoGenerate={() => onAutoGenerateSample(editing)}
            onRunTest={onRunTest}
            isTesting={isTesting}
            testResult={testResult}
          />

          <Stack direction="row" spacing={1.5} sx={{ mt: 3 }}>
            <Tooltip title={lockedHint}>
              <span>
                <Button variant="contained" disabled={!canEditRules || isSaving} onClick={onSave}>
                  Save rule
                </Button>
              </span>
            </Tooltip>
            {!editing.rule_id.startsWith('new_rule_') && (
              <Button
                variant="outlined"
                color="error"
                disabled={!canEditRules || isDeleting}
                onClick={() => onRequestDelete(editing.rule_id)}
              >
                Delete rule
              </Button>
            )}
            <Button color="inherit" onClick={onClose}>
              Cancel
            </Button>
          </Stack>
        </Box>
      )}
    </Drawer>
  );
}

RuleEditorDrawer.propTypes = {
  editing: PropTypes.object,
  onChangeEditing: PropTypes.func.isRequired,
  onClose: PropTypes.func.isRequired,
  onUpdateConditions: PropTypes.func.isRequired,
  canEditRules: PropTypes.bool.isRequired,
  lockedHint: PropTypes.string.isRequired,
  sample: PropTypes.string.isRequired,
  onSampleChange: PropTypes.func.isRequired,
  onAutoGenerateSample: PropTypes.func.isRequired,
  onRunTest: PropTypes.func.isRequired,
  isTesting: PropTypes.bool.isRequired,
  testResult: PropTypes.object,
  isSaving: PropTypes.bool.isRequired,
  isDeleting: PropTypes.bool.isRequired,
  onSave: PropTypes.func.isRequired,
  onRequestDelete: PropTypes.func.isRequired,
};
